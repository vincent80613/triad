export function translate(language: LanguageCode, key: keyof typeof en): string {
  if (language === 'en') return en[key]
  return packs[language]?.[key] ?? en[key]
}

export function useT(): (key: keyof typeof en) => string {
  const language = useApp((state) => state.settings.language)
  return useCallback((key: keyof typeof en) => translate(language, key), [language])
}
